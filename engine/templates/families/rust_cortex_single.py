"""Bare-metal Rust single-core template family (req-029).

Keeps the single-package layout (``Cargo.toml`` + ``src/main.rs``) and consumes
the shared ``ProjectPlan``: pack LED blink, ``flip-link``, ``opt-level = "s"``,
and a probe-rs VS Code config with the pack SVD.
"""

from __future__ import annotations

import json
from pathlib import Path

from engine.core.model import Device
from engine.core.plan import ProjectPlan
from engine.templates.families import (
    RenderOptions,
    register_template_family,
)
from engine.templates.families.rust_common import hex32 as _hex, main_rs, tpl as _tpl

__all__ = ["RustCortexSingleFamily"]


class RustCortexSingleFamily:
    """Render one cargo package from the shared plan."""

    def emit(
        self,
        device: Device,
        plan: ProjectPlan,
        out: Path,
        options: RenderOptions,
    ) -> list[Path]:
        from engine.templates import renderer as r

        core = plan.primary
        if core.flash is None or core.ram is None:
            raise ValueError(
                f"pack {device.id!r} core {core.name!r} has no flash/RAM region"
            )
        out.mkdir(parents=True, exist_ok=True)
        written: list[Path] = []

        def write(rel: str, text: str) -> None:
            path = out / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            written.append(path)

        write(".mu/stack", "cargo-cortex\n")
        write(".gitignore", "target/\nbuild/\n.mu/\n")

        oc = device.openocd
        if oc is not None:
            write("probe/openocd.cfg", r._render_openocd(device))
            write("probe/probe-serial.cfg", r._probe_serial(device))

        if device.facets.block_for("config_headers") is not None:
            cfg = r._config_ctx(device)
            write("config/OVERRIDES.md", r._OVERRIDES.substitute(cfg))
            write(f"config/{cfg['config_header']}", r._CONFIG_H.substitute(cfg))

        chip = (
            device.facets.probe_setting("probe-rs", "chip")
            if device.facets
            else None
        ) or device.id
        write(
            "Cargo.toml",
            _tpl(
                """[package]
name = "@PKG@"
version = "0.1.0"
edition = "2021"
rust-version = "1.99"
build = "build.rs"

[dependencies]
cortex-m = "=0.7.9"
cortex-m-rt = "=0.7.7"
panic-halt = "=1.0.0"

[profile.dev]
# C++ parity: -Os. The NOP blink is visibly too slow at opt-level 0.
panic = "abort"
opt-level = "s"
debug = true

[profile.release]
panic = "abort"
opt-level = "z"
codegen-units = 1
lto = true
debug = true
""",
                PKG=device.id,
            ),
        )
        write(
            ".cargo/config.toml",
            _tpl(
                """# Generated by mu — pin the target and the link-time stack guard.
[build]
target = "@ARCH@"

[target.@ARCH@]
linker = "flip-link"
runner = "probe-rs run --chip @CHIP@"
""",
                ARCH=core.arch,
                CHIP=chip,
            ),
        )
        write(
            "build.rs",
            """//! Generated by mu — place memory.x and link with cortex-m-rt's link.x.
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::copy("memory.x", out.join("memory.x")).unwrap();
    println!("cargo:rustc-link-search={}", out.display());
    println!("cargo:rustc-link-arg=-Tlink.x");
    println!("cargo:rerun-if-changed=memory.x");
}
""",
        )
        write(
            "memory.x",
            _tpl(
                """/* @PROJECT@ / @CORE@ — generated from the pack memory map. */
MEMORY
{
  FLASH (rx) : ORIGIN = @FLASH_ORIGIN@, LENGTH = @FLASH_LEN@
  RAM (rwx)  : ORIGIN = @RAM_ORIGIN@, LENGTH = @RAM_LEN@
}

_stack_start = ORIGIN(RAM) + LENGTH(RAM);
""",
                PROJECT=device.id,
                CORE=core.name,
                FLASH_ORIGIN=_hex(core.flash.origin),
                FLASH_LEN=core.flash.size,
                RAM_ORIGIN=_hex(core.ram.origin),
                RAM_LEN=core.ram.size,
            ),
        )
        write("src/main.rs", main_rs(core))
        write("README.md", self._readme(device, plan, chip))

        if options.vscode and oc is not None:
            written.extend(r.fetch_svds(device, out))
            for rel, text in self._vscode(device, plan, chip).items():
                write(rel, text)

        return sorted(written)

    def _vscode(self, device: Device, plan: ProjectPlan, chip: str) -> dict[str, str]:
        core = plan.primary
        elf = f"target/{core.arch}/debug/{device.id}"
        svd = Path(core.svd_path).name if core.svd_path else None
        launch = {
            "type": "probe-rs-debug",
            "request": "launch",
            "name": f"Debug {core.name} (probe-rs)",
            "cwd": "${workspaceFolder}",
            "chip": chip,
            "flashingConfig": {"flashingEnabled": True},
            "coreConfigs": [
                {
                    "coreIndex": core.processor_index,
                    "programBinary": f"${{workspaceFolder}}/{elf}",
                    **(
                        {"svdFile": f"${{workspaceFolder}}/probe/{svd}"}
                        if svd
                        else {}
                    ),
                }
            ],
            "preLaunchTask": "Build",
            "consoleLogLevel": "Console",
        }
        tasks = {
            "version": "2.0.0",
            "tasks": [
                {
                    "label": "Build",
                    "type": "process",
                    "command": "cargo",
                    "args": ["build"],
                    "group": {"kind": "build", "isDefault": True},
                },
                {
                    "label": "Clean",
                    "type": "process",
                    "command": "cargo",
                    "args": ["clean"],
                },
                {
                    "label": "Flash",
                    "type": "process",
                    "command": "probe-rs",
                    "args": ["download", "--chip", chip, elf],
                },
                {
                    "label": "Run",
                    "type": "process",
                    "command": "probe-rs",
                    "args": ["run", "--chip", chip, elf],
                },
            ],
        }

        def j(obj: object) -> str:
            return json.dumps(obj, indent=2) + "\n"

        return {
            ".vscode/launch.json": j({"version": "0.2.0", "configurations": [launch]}),
            ".vscode/tasks.json": j(tasks),
            ".vscode/settings.json": j({}),
            ".vscode/extensions.json": j(
                {
                    "recommendations": [
                        "probe-rs.probe-rs-debugger",
                        "rust-lang.rust-analyzer",
                    ]
                }
            ),
        }

    def _readme(self, device: Device, plan: ProjectPlan, chip: str) -> str:
        core = plan.primary
        led = core.example_led is not None
        return _tpl(
            """# @PROJECT@

Generated by **mu** from the `@PROJECT@` pack (v@VERSION@), Rust (bare metal).

- core: `@CORE@` (@ARCH@)
- example: @EXAMPLE@

## Build and flash

```sh
mu build --project-dir .      # cargo build in the pinned image
cargo build                   # or on a host with the target + flip-link
```

Flash/debug with probe-rs (already in the image):

```sh
probe-rs run --chip @CHIP@ target/@ARCH@/debug/@PROJECT@
```

`mu flash --project-dir . --files target/@ARCH@/debug/@PROJECT@` also works via
OpenOCD.

## Debug in VS Code

`mu create --vscode` wrote `.vscode/` with **probe-rs-debug** (one core config,
@SVD@). `F5` builds, flashes, and runs.

## Expected behaviour

@EXPECTED@

## Notes

- This is a bare-metal scaffold: clocks, UART, peripherals, and the radio are
  yours to write.
- `flip-link` moves the stack below `.bss`; keep it installed in the toolchain
  image.
""",
            PROJECT=device.id,
            VERSION=device.version,
            CORE=core.name,
            ARCH=core.arch,
            CHIP=chip,
            SVD=(Path(core.svd_path).name if core.svd_path else "no SVD"),
            EXAMPLE=("on-board LED" if led else "watchable `COUNTER` loop"),
            EXPECTED=(
                "- The on-board LED blinks at ~2 Hz.\n"
                if led
                else "- The core runs a watchable `COUNTER` loop.\n"
            ),
        )


register_template_family("rust-cortex", RustCortexSingleFamily())
