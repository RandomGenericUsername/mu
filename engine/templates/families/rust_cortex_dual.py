"""Bare-metal Rust dual-core template family (req-028).

One cargo package per core, a generated Makefile for build/flash, raw-register
PB15 blink + sibling counter, and a ``probe-rs-debug`` VS Code config. No HAL,
no Embassy; the user writes the firmware.

Layout and semantics were validated live on NUCLEO-WL55JC (see
``tickets/req-028-rust-dual-core/ticket.md``).
"""

from __future__ import annotations

import json
from pathlib import Path

from engine.core.model import Device
from engine.core.plan import CorePlan, ProjectPlan
from engine.templates.families import (
    RenderOptions,
    register_template_family,
)

from engine.templates.families.rust_common import (
    hex32 as _hex,
    main_rs,
    pre_init,
    tpl as _tpl,
)

__all__ = ["RustCortexDualFamily"]


class RustCortexDualFamily:
    """Render a bare-metal, per-core Rust project from the shared plan."""

    def emit(
        self,
        device: Device,
        plan: ProjectPlan,
        out: Path,
        options: RenderOptions,
    ) -> list[Path]:
        from engine.templates import renderer as r

        out.mkdir(parents=True, exist_ok=True)
        written: list[Path] = []

        def write(rel: str, text: str) -> None:
            path = out / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            written.append(path)

        write(".mu/stack", "cargo-cortex-dual\n")
        write(".gitignore", "build/\n.mu/\ntarget/\n**/target/\n")

        oc = device.openocd
        if oc is not None:
            write("probe/openocd.cfg", r._render_openocd(device))
            write("probe/probe-serial.cfg", r._probe_serial(device))
            if oc.dual_core and not oc.board:
                write("probe/dual-core.cfg", r._dual_core_cfg(device))

        if device.facets.block_for("config_headers") is not None:
            cfg = r._config_ctx(device)
            write("config/OVERRIDES.md", r._OVERRIDES.substitute(cfg))
            write(f"config/{cfg['config_header']}", r._CONFIG_H.substitute(cfg))

        for core in plan.cores:
            self._emit_core(device, core, out, write)

        write("Makefile", self._makefile(device, plan, r))
        write("README.md", self._readme(device, plan))

        if options.vscode and oc is not None:
            written.extend(r.fetch_svds(device, out))
            for rel, text in self._vscode(device, plan).items():
                write(rel, text)

        return sorted(written)

    # --- per-core cargo package -------------------------------------------

    def _emit_core(self, device: Device, core: CorePlan, out: Path, write) -> None:
        if core.flash is None or core.ram is None:
            raise ValueError(
                f"pack {device.id!r} core {core.name!r} has no flash/RAM region; "
                "cargo-cortex-dual requires per-core memory regions"
            )
        package = f"{device.id}-{core.slug}"
        write(
            f"{core.slug}/Cargo.toml",
            _tpl(
                """[package]
name = "@PKG@"
version = "0.1.0"
edition = "2021"
rust-version = "1.99"
build = "build.rs"

[dependencies]
cortex-m = "=0.7.9"
cortex-m-rt = "=0.7.7"
panic-halt = "=1.0.0"

[profile.dev]
# C++ parity: -Os. The NOP blink is visibly too slow at opt-level 0.
panic = "abort"
opt-level = "s"
debug = true

[profile.release]
panic = "abort"
opt-level = "z"
codegen-units = 1
lto = true
debug = true
""",
                PKG=package,
            ),
        )
        write(
            f"{core.slug}/.cargo/config.toml",
            _tpl(
                """# Generated by mu — pin the target and the link-time stack guard.
[build]
target = "@ARCH@"

[target.@ARCH@]
linker = "flip-link"
""",
                ARCH=core.arch,
            ),
        )
        write(
            f"{core.slug}/build.rs",
            """//! Generated by mu — place memory.x and link with cortex-m-rt's link.x.
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::copy("memory.x", out.join("memory.x")).unwrap();
    println!("cargo:rustc-link-search={}", out.display());
    println!("cargo:rustc-link-arg=-Tlink.x");
    println!("cargo:rerun-if-changed=memory.x");
}
""",
        )
        write(
            f"{core.slug}/memory.x",
            _tpl(
                """/* @PROJECT@ / @CORE@ — generated from the pack memory map. */
MEMORY
{
  FLASH (rx) : ORIGIN = @FLASH_ORIGIN@, LENGTH = @FLASH_LEN@
  RAM (rwx)  : ORIGIN = @RAM_ORIGIN@, LENGTH = @RAM_LEN@
}

_stack_start = ORIGIN(RAM) + LENGTH(RAM);
""",
                PROJECT=device.id,
                CORE=core.name,
                FLASH_ORIGIN=_hex(core.flash.origin),
                FLASH_LEN=core.flash.size,
                RAM_ORIGIN=_hex(core.ram.origin),
                RAM_LEN=core.ram.size,
            ),
        )
        write(f"{core.slug}/src/main.rs", main_rs(core))

    # --- generated build/flash driver -------------------------------------

    def _makefile(self, device: Device, plan: ProjectPlan, r) -> str:
        package = lambda c: f"{device.id}-{c.slug}"
        elf = lambda c: f"build/{c.name}/{device.id}-{c.name}.elf"
        args = r._oc_flash_args(device)

        sections = []
        for core in plan.cores:
            # H755 (independent dual) exposes cpu0/cpu1: select this core
            # before program + boot check. cpu2_boot packs stay single-core.
            target_line = (
                f" -c 'targets {core.openocd_target}'"
                if plan.flash.dual_core
                and not plan.flash.single_core
                and core.openocd_target
                else ""
            )
            sections.append(
                _tpl(
                    """# --- core @CORE@ (@ARCH@) ---
build-@CORE@:
	cd @SLUG@ && cargo build
	@mkdir -p build/@CORE@
	cp @SLUG@/target/@ARCH@/debug/@PKG@ @ELF@

flash-@CORE@: build-@CORE@
	$(OPENOCD) @ARGS@@TARGET@ -c "program @ELF@ verify reset" @BOOTCHECK@ -c "exit"

clean-@CORE@:
	cd @SLUG@ && cargo clean
	rm -rf build/@CORE@

""",
                    CORE=core.name,
                    ARCH=core.arch,
                    SLUG=core.slug,
                    PKG=package(core),
                    ELF=elf(core),
                    ARGS=args,
                    TARGET=target_line,
                    BOOTCHECK=(
                        r._boot_check_cmds(device, core.name)
                        if core.name == plan.primary.name
                        or not plan.primary.release_writes
                        else ""
                    ),
                )
            )

        build_targets = " ".join(f"build-{c.name}" for c in plan.cores)
        flash_targets = " ".join(f"flash-{name}" for name in plan.flash.order)
        clean_targets = " ".join(f"clean-{c.name}" for c in plan.cores)
        sibling = r._sibling_debug_section(device) if plan.sibling else ""
        phony = " ".join(
            ["all", "build", "flash", "clean", build_targets, flash_targets, clean_targets]
        )
        if plan.sibling:
            phony += f" debug-{plan.sibling.slug}"

        return (
            _tpl(
                """# Makefile for @PROJECT@ — generated from the pack; do not edit by hand.
# Bare-metal Rust: one cargo package per core, built for its own target.
OPENOCD ?= openocd

""",
                PROJECT=device.id,
            )
            + "\n".join(sections)
            + sibling
            + _tpl(
                """ALL_BUILD = @BUILD@
ALL_FLASH = @FLASH@
ALL_CLEAN = @CLEAN@

all: build

build: $(ALL_BUILD)

flash: $(ALL_FLASH)

clean: $(ALL_CLEAN)

.PHONY: @PHONY@
""",
                BUILD=build_targets,
                FLASH=flash_targets,
                CLEAN=clean_targets,
                PHONY=phony,
            )
        )

    # --- VS Code / probe-rs ------------------------------------------------

    def _vscode(self, device: Device, plan: ProjectPlan) -> dict[str, str]:
        chip = (
            device.facets.probe_setting("probe-rs", "chip")
            if device.facets
            else None
        ) or device.id
        svd_name = lambda c: Path(c.svd_path).name if c.svd_path else None

        def core_cfg(core: CorePlan) -> dict:
            entry = {
                "coreIndex": core.processor_index,
                "programBinary": f"${{workspaceFolder}}/build/{core.name}/{device.id}-{core.name}.elf",
            }
            if svd_name(core):
                entry["svdFile"] = f"${{workspaceFolder}}/probe/{svd_name(core)}"
            return entry

        configs: list[dict] = []
        for index, core in enumerate(plan.cores):
            configs.append(
                {
                    "type": "probe-rs-debug",
                    "request": "attach" if plan.debug.attach_only else "launch",
                    "name": f"Debug {core.name} (probe-rs)",
                    "cwd": "${workspaceFolder}",
                    "chip": chip,
                    "flashingConfig": {"flashingEnabled": False},
                    "coreConfigs": [core_cfg(core)],
                    "preLaunchTask": "Flash" if index == 0 else "Build",
                    "consoleLogLevel": "Console",
                }
            )

        if len(plan.cores) > 1:
            compound = {
                "type": "probe-rs-debug",
                "request": "attach" if plan.debug.attach_only else "launch",
                "name": "Debug " + "+".join(c.name for c in plan.cores) + " (probe-rs)",
                "cwd": "${workspaceFolder}",
                "chip": chip,
                "flashingConfig": {"flashingEnabled": False},
                "coreConfigs": [core_cfg(c) for c in plan.cores],
                "preLaunchTask": "Flash",
                "consoleLogLevel": "Console",
            }
            configs.append(compound)

        tasks = [
            {
                "label": "Build",
                "type": "process",
                "command": "make",
                "args": ["build"],
                "group": {"kind": "build", "isDefault": True},
            },
            {
                "label": "Clean",
                "type": "process",
                "command": "make",
                "args": ["clean"],
            },
            {
                "label": "Flash",
                "type": "process",
                "command": "make",
                "args": ["flash"],
                "dependsOrder": "sequence",
                "dependsOn": ["Clean", "Build"],
            },
        ]
        for core in plan.cores:
            tasks.append(
                {
                    "label": f"Flash {core.name}",
                    "type": "process",
                    "command": "make",
                    "args": [f"flash-{core.name}"],
                }
            )

        def j(obj: object) -> str:
            return json.dumps(obj, indent=2) + "\n"

        return {
            ".vscode/launch.json": j({"version": "0.2.0", "configurations": configs}),
            ".vscode/tasks.json": j({"version": "2.0.0", "tasks": tasks}),
            ".vscode/settings.json": j({}),
            ".vscode/extensions.json": j(
                {
                    "recommendations": [
                        "probe-rs.probe-rs-debugger",
                        "rust-lang.rust-analyzer",
                    ]
                }
            ),
        }

    # --- project README ----------------------------------------------------

    def _readme(self, device: Device, plan: ProjectPlan) -> str:
        cores = ", ".join(f"`{c.name}` ({c.arch})" for c in plan.cores)
        led = plan.primary.example_led is not None
        return _tpl(
            """# @PROJECT@

Generated by **mu** from the `@PROJECT@` pack (v@VERSION@), Rust (bare metal).

- cores: @CORES@
- primary example: @EXAMPLE@
- sibling cores: `COUNTER` loop (watch it in the debugger)

## Build and flash

```sh
make build                 # builds every core
mu build --project-dir .   # same, in the pinned image
make flash                 # sibling(s) first, then the primary
```

Each core is a normal cargo package: `cd <core> && cargo build`.

## Debug in VS Code

`mu create --vscode` wrote `.vscode/` with **probe-rs-debug**. Flash runs as a
pre-launch task; the launch configs attach per core (and a combined one for all
cores). Use `probe-rs`'s per-core `coreConfigs`; SVDs are in `probe/`.

## Expected behaviour

@EXPECTED@
- Sibling cores run a watchable `COUNTER`.
@RELEASE@
## Notes

- This is a bare-metal scaffold: clocks, UART, peripherals, and the radio are
  yours to write.
- `__pre_init` (when generated) releases CPU2 before `main`; it uses only raw
  register addresses.
""",
            PROJECT=device.id,
            VERSION=device.version,
            CORES=cores,
            EXAMPLE=("on-board LED" if led else "COUNTER loop"),
            EXPECTED=(
                "- The on-board LED blinks at ~2 Hz on the primary core.\n"
                if led
                else "- The primary core runs a watchable `COUNTER` loop.\n"
            ),
            RELEASE=(
                "- The primary releases CPU2 (`SBRV` + `C2BOOT`) before `main`.\n"
                if plan.primary.release_writes
                else ""
            ),
        )


register_template_family("rust-cortex-dual", RustCortexDualFamily())
