"""ESP-IDF Rust template family (req-030).

Uses ``esp-idf-svc``/``esp-idf-hal`` on the Xtensa target. The official
``espressif/idf-rust`` image carries Rust, espflash and the Xtensa toolchain;
``esp-idf-sys`` downloads IDF v6.1 into the project ``.embuild`` on first build.
"""

from __future__ import annotations

import json
from pathlib import Path

from engine.core.model import Device
from engine.core.plan import ProjectPlan
from engine.templates.families import (
    RenderOptions,
    register_template_family,
)

__all__ = ["EspIdfRustFamily"]

#: Pinned IDF version (spike-009 built esp-idf-sys against v6.1).
IDF_VERSION = "v6.1"


def _tpl(text: str, **kw: object) -> str:
    for key, value in kw.items():
        text = text.replace(f"@{key}@", str(value))
    return text


class EspIdfRustFamily:
    """Render a cargo ESP-IDF Rust app from the shared plan."""

    def emit(
        self,
        device: Device,
        plan: ProjectPlan,
        out: Path,
        options: RenderOptions,
    ) -> list[Path]:
        out.mkdir(parents=True, exist_ok=True)
        written: list[Path] = []

        def write(rel: str, text: str) -> None:
            path = out / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            written.append(path)

        led = device.facets.block_for("example_led") or {}
        gpio = int(led.get("gpio", 2))
        active = led.get("active", "high")
        sdk = device.facets.block_for("sdkconfig") or {}
        target = sdk.get("target", "esp32")
        port = device.probe_ref.address or "/dev/ttyUSB0"
        elf = f"target/xtensa-esp32-espidf/debug/{device.id}"

        write(".mu/stack", "esp-idf-rust\n")
        write(".gitignore", "target/\n.embuild/\nbuild/\n.mu/\n")
        write(
            "Cargo.toml",
            _tpl(
                """[package]
name = "@PROJECT@"
version = "0.1.0"
edition = "2021"
resolver = "2"
rust-version = "1.82"

[[bin]]
name = "@PROJECT@"
harness = false

[profile.release]
opt-level = "s"

[profile.dev]
debug = true
opt-level = "z"

[dependencies]
log = "0.4"
esp-idf-svc = { version = "0.53", features = ["critical-section", "embassy-time-driver", "embassy-sync"] }
embassy-time = { version = "0.5", features = ["generic-queue-8"] }

[build-dependencies]
embuild = "0.33.5"
""",
                PROJECT=device.id,
            ),
        )
        write(
            "build.rs",
            "fn main() {\n    embuild::espidf::sysenv::output();\n}\n",
        )
        write(
            ".cargo/config.toml",
            _tpl(
                """# Generated by mu — ESP-IDF Rust on Xtensa.
[build]
target = "xtensa-esp32-espidf"

[target.'cfg(target_os = "espidf")']
linker = "ldproxy"
runner = "espflash flash --monitor"
rustflags = ["--cfg", "espidf_time64"]

[unstable]
build-std = ["std", "panic_abort"]

[env]
MCU = "@TARGET@"
ESP_IDF_VERSION = "@IDF@"
""",
                TARGET=target,
                IDF=IDF_VERSION,
            ),
        )
        write(
            "src/main.rs",
            _tpl(
                """use std::time::Duration;

use esp_idf_svc::hal::gpio::PinDriver;
use esp_idf_svc::hal::peripherals::Peripherals;

fn main() {
    esp_idf_svc::sys::link_patches();
    esp_idf_svc::log::EspLogger::initialize_default();

    let p = Peripherals::take().unwrap();
    let mut led = PinDriver::output(p.pins.gpio@gpio@).unwrap();
    let mut n = 0u32;
    loop {
        n += 1;
        log::info!("@PROJECT@: blink {}", n);
        led.@ON@().unwrap();
        std::thread::sleep(Duration::from_millis(500));
        led.@OFF@().unwrap();
        std::thread::sleep(Duration::from_millis(500));
    }
}
""",
                gpio=gpio,
                PROJECT=device.id,
                ON="set_low" if active == "low" else "set_high",
                OFF="set_high" if active == "low" else "set_low",
            ),
        )
        write("README.md", self._readme(device, gpio, active, target, port, elf))

        if options.vscode:
            for rel, text in self._vscode(device, target, port, elf).items():
                write(rel, text)

        return sorted(written)

    def _vscode(
        self, device: Device, target: str, port: str, elf: str
    ) -> dict[str, str]:
        tasks = {
            "version": "2.0.0",
            "tasks": [
                {
                    "label": "Build",
                    "type": "process",
                    "command": "cargo",
                    "args": ["build"],
                    "group": {"kind": "build", "isDefault": True},
                },
                {
                    "label": "Clean",
                    "type": "process",
                    "command": "cargo",
                    "args": ["clean"],
                },
                {
                    "label": "Flash",
                    "type": "process",
                    "command": "espflash",
                    "args": ["flash", "--port", port, "--chip", target, elf],
                },
                {
                    "label": "Monitor",
                    "type": "process",
                    "command": "espflash",
                    "args": ["monitor", port],
                },
            ],
        }

        def j(obj: object) -> str:
            return json.dumps(obj, indent=2) + "\n"

        return {
            ".vscode/tasks.json": j(tasks),
            ".vscode/extensions.json": j(
                {"recommendations": ["rust-lang.rust-analyzer"]}
            ),
        }

    def _readme(
        self, device: Device, gpio: int, active: str, target: str, port: str, elf: str
    ) -> str:
        return _tpl(
            """# @PROJECT@

Generated by **mu** from the `@PROJECT@` pack (v@VERSION@), Rust (ESP-IDF).

- target: `@TARGET@` (`xtensa-esp32-espidf`)
- example: GPIO@gpio@ LED blink (@ACTIVE@ active), log on UART0 115200

## Build

```sh
mu build --project-dir .     # cargo build in the pinned idf-rust image
cargo build                  # first build downloads IDF to .embuild
```

## Flash / monitor

The ESP32-CAM has no auto-reset: **GPIO0→GND + RESET** for download mode,
then release GPIO0 + RESET to run.

```sh
mu flash --lang rust --project-dir . --files @ELF@
espflash flash --port @PORT@ --chip @TARGET@ @ELF@
espflash monitor @PORT@
```

`mu flash` uses the `espflash` backend for this stack; C/C++ keep esptool.

## Notes

- This is a bring-up scaffold: WiFi, camera, peripherals are yours to write.
- `.embuild/` and `target/` are gitignored; the first build is large.
""",
            PROJECT=device.id,
            VERSION=device.version,
            TARGET=target,
            gpio=gpio,
            ACTIVE=active,
            PORT=port,
            ELF=elf,
        )


register_template_family("esp-idf-rust", EspIdfRustFamily())
